Talk(70, "我不该？")
Talk(70, "他要杀我。我不往家里跑，往哪里跑？")
Talk(70, "师父为他拼掉半条命，到头来怪我引狼入室。", EXPR.sad)
Talk(70, "我一个人在山下那些年，谁替我记过一句好。")
Talk(0, "（她说得很慢，说到最后，声音有点抖。）", EXPR.think)
Talk(70, "……罢了。旧账翻不完。心经拿来。")
Talk(0, "孙婆婆死了。")
Talk(70, "全真教打死的。这笔账别安到我头上。")
Talk(70, "倒是你——全真教不要的野种，也配站在这墓里？")
Talk(0, "（我把话咽了回去。手已经按在剑柄上。）", EXPR.think)
Talk(70, "想动手？")
Talk(70, "好。二十年前我走出这道门的时候，也是你这副不服气的样子。")
if TryBattle(203) == true then
    Talk(0, "（拂尘扫过来的时候，我一剑挑开了她的袖子。）", EXPR.think)
    Talk(70, "……好小子，有点门道。")
    Talk(22, "师姐，够了。")
    Talk(70, "哼。师妹，你护着他？")
    AddExp(0, 300)
else
    Talk(0, "（我连她一掌都接不住。）", EXPR.think)
    Talk(0, "（胸口像被铁尺抽了一下，人已经贴到了石壁上。）", EXPR.think)
    Talk(70, "凭你也想拦我？")
    Talk(70, "今日看在我师妹面上，饶你一命。")
    Talk(22, "李莫愁。")
