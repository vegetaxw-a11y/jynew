Talk(0, "等什么？")
Talk(22, "等石头落下来。")
Talk(0, "（石头落下来了。很慢，很沉，最后一声，整座墓都颤了一下。）", EXPR.think)
Talk(0, "（灰尘在灯下浮着，久久不落。）", EXPR.think)
