if GetFlagInt("庙祝指路") == 1 then
    Talk(111, "去罢去罢，别在这儿碍着我扫地。")
    do return end
end
Talk(111, "小娃娃，又来庙里躲雨？")
Talk(0, "老庙祝，我爹当年是不是就死在这庙里？")
Talk(111, "你爹？……那年秋天的事，我记不真了。只记得庙里来过好些带刀的人，闹了一整夜。")
Talk(0, "都是些什么人？")
Talk(111, "我一个烧香的，哪里敢细看。倒是后来听说，你娘抱着你，连夜就走了。")
Talk(0, "……")
if GetFlagInt("父亲遗物") == 0 then
    Talk(111, "你要真想知道，去把那供桌上的旧木箱翻一翻，兴许还留着什么。")
    do return end
end
Talk(111, "你怀里那半截铁片……倒像是当年那位杨爷的东西。")
Talk(0, "你认得？")
Talk(111, "我不过是个庙祝，认得什么。只记得那位杨爷有个总穿白袍的兄弟，隔三差五来看他。")
Talk(0, "（白袍……娘也说过这个人。）", EXPR.think)
